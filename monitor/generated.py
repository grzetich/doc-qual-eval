"""Recognising files nobody edits by hand.

A run against the Anthropic Python SDK drafted twelve patches, all of them in
`CHANGELOG.md`, all correct, all worthless. That file is produced by a code
generator, so any patch is overwritten the next time it runs. The patches were
locally valid and globally pointless, which is the same shape of error as
proposing a login URL: the check passed and the output was still wrong.

Two ways to spot these. Generators usually announce themselves in a header, so
a marker scan catches most of them without configuration. The rest need naming
in `targets.yml`.

Changelogs are excluded by default whether or not a generator made them. A
changelog is a record of what happened, and correcting a link in a three year
old entry edits history to no one's benefit.
"""

from __future__ import annotations

import fnmatch
from pathlib import Path

#: Phrases generators put at the top of their output. Matched case
#: insensitively against the first part of the file.
MARKERS = (
    "@generated",
    "code generated by",
    "do not edit",
    "don't edit",
    "automatically generated",
    "autogenerated",
    "auto-generated",
    "this file was generated",
    "generated by openapi",
    "generated by stainless",
)

#: Excluded everywhere unless a target overrides it. Changelogs are history,
#: lockfiles are machine state, and vendored trees belong to someone else.
DEFAULT_EXCLUDES = (
    "CHANGELOG.md", "CHANGELOG", "**/CHANGELOG.md",
    "HISTORY.md", "**/HISTORY.md",
    "**/node_modules/**", "**/vendor/**", "**/dist/**", "**/build/**",
    "*.lock", "**/*.lock",
)

#: How much of the file to read looking for a marker.
HEADER_BYTES = 800


def is_generated(path: Path, rel: str, extra_patterns: tuple[str, ...] = ()
                 ) -> tuple[bool, str]:
    """Return (excluded, reason) for one file."""
    patterns = tuple(DEFAULT_EXCLUDES) + tuple(extra_patterns)
    for pattern in patterns:
        if fnmatch.fnmatch(rel, pattern) or fnmatch.fnmatch(Path(rel).name, pattern):
            return True, f"matches excluded pattern '{pattern}'"

    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            header = fh.read(HEADER_BYTES).lower()
    except OSError:
        return False, ""

    for marker in MARKERS:
        if marker in header:
            return True, f"header declares it generated ('{marker}')"
    return False, ""


def filter_files(files: list[tuple[str, Path]], extra_patterns: tuple[str, ...] = ()
                 ) -> tuple[list[tuple[str, Path]], list[tuple[str, str]]]:
    """Split files into those worth checking and those that are generated."""
    keep: list[tuple[str, Path]] = []
    dropped: list[tuple[str, str]] = []
    for rel, path in files:
        excluded, reason = is_generated(path, rel, extra_patterns)
        if excluded:
            dropped.append((rel, reason))
        else:
            keep.append((rel, path))
    return keep, dropped
